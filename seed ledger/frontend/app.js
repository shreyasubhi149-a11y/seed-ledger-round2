function filterLots() {
  if (!$("#search")) return;

  const query = $("#search").value.trim().toLocaleLowerCase();
  const availability = $("#availability").value;
  const minimum = Number($("#mingerm").value);
  const sort = $("#sort").value;
  const saved = savedIds();

  const rows = state.lots.filter((lot) => {
    const haystack =
      `${lot.variety} ${lot.species || ""} ${lot.owner_name || ""}`
        .toLocaleLowerCase();

    return haystack.includes(query) &&
      (
        availability !== "available" ||
        (lot.available_seeds > 0 && lot.is_available)
      ) &&
      (availability !== "mine" || lot.owner_id === state.me?.id) &&
      (availability !== "saved" || saved.includes(lot.id)) &&
      (minimum === 0 || (lot.avg_germination_rate ?? -1) >= minimum);
  });

  const sorters = {
    new: (a, b) => b.id - a.id,
    name: (a, b) =>
      a.variety.localeCompare(b.variety, LOCALES[language]),
    stock: (a, b) => b.available_seeds - a.available_seeds,
    germ: (a, b) =>
      (b.avg_germination_rate ?? -1) -
      (a.avg_germination_rate ?? -1),
  };

  rows.sort(sorters[sort] || sorters.new);

  $("#mingerm-val").textContent = n(minimum);
  $("#filter-count").textContent = t("results", {
    n: n(rows.length),
    total: n(state.lots.length),
  });

  $("#catalogue-cards").innerHTML =
    rows.map(lotCard).join("") ||
    `<p class="empty">${t("noResults")}</p>`;
}

