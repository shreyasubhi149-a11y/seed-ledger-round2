function errorKey(error) {
  if (error.key) return error.key;

  return ({
    400: "invalid",
    401: "authError",
    403: "forbidden",
    404: "notFound",
    409: "conflict",
    422: "invalid",
    429: "serverError",
  })[error.status] || "serverError";
}

function showError(error) {
  noticeKey = errorKey(error);
  $("#error").textContent = t(noticeKey);
  $("#error").hidden = false;
  console.error(error);
}

function toast(key, values = {}) {
  clearTimeout(toastTimer);
  $("#toast").textContent = t(key, values);
  $("#toast").hidden = false;

  toastTimer = setTimeout(() => {
    $("#toast").hidden = true;
  }, 4000);
}

async function api(path, options = {}) {
  let response;

  try {
    response = await fetch(path, {
      ...options,
      headers: {
        ...(options.body
          ? { "Content-Type": "application/json" }
          : {}),
        ...(state.token
          ? { Authorization: `Bearer ${state.token}` }
          : {}),
        ...(options.headers || {}),
      },
    });
  } catch {
    const error = new Error("Connection failed");
    error.key = "connectionError";
    throw error;
  }

  if (!response.ok) {
    const error = new Error(`HTTP ${response.status}`);
    error.status = response.status;

    try {
      error.details = await response.json();
    } catch {}

    throw error;
  }

  return response.status === 204
    ? null
    : response.json();
}

