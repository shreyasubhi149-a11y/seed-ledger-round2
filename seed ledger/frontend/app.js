/* ---------- Notifications ---------- */

function inboxItems() {
  if (!state.me) return [];

  const items = [];

  state.requests
    .filter((item) =>
      item.owner_id === state.me.id && item.status === "pending")
    .forEach((item) => {
      items.push({
        text: t("requestSentence", {
          name: item.requester_name,
          n: n(item.quantity),
          owner: item.owner_name,
        }),
        html: `<button class="small" data-inbox="requests">
          ${t("view")}
        </button>`,
      });
    });

  state.lots
    .filter((lot) => lot.owner_id === state.me.id)
    .forEach((lot) => {
      if (lot.available_seeds < 50) {
        items.push({
          text: t("lowStock", {
            name: lot.variety,
            n: n(lot.available_seeds),
          }),
          html: button("stock", lot.id, "manage"),
        });
      }

      if (!lot.report_count) {
        items.push({
          text: `${lot.variety}: ${t("missingInfo")}`,
          html: button("report", lot.id, "addReport"),
        });
      }

      if (
        lot.date_saved &&
        (Date.now() - new Date(lot.date_saved).getTime()) /
          86400000 > 365
      ) {
        items.push({
          text: `${lot.variety}: ${t("storageReviewInfo")}`,
          html: button("report", lot.id, "addReport"),
        });
      }
    });

  return items;
}

