function drawGraph() {
  const nodes = state.graph.nodes || [];
  const edges = state.graph.edges || [];

  if (!nodes.length) {
    $("#network-graph").textContent = t("empty");
    return;
  }

  const positions = new Map(nodes.map((node, index) => [
    node.id,
    {
      x: 400 + Math.cos(index * Math.PI * 2 / nodes.length) * 250,
      y: 210 + Math.sin(index * Math.PI * 2 / nodes.length) * 140,
    },
  ]));

  $("#network-graph").innerHTML = `
    <svg class="graph" viewBox="0 0 800 430"
      role="img" aria-label="${t("network")}">
      ${edges.map((edge) => {
        const a = positions.get(edge.from_grower_id);
        const b = positions.get(edge.to_grower_id);

        return a && b
          ? `<line x1="${a.x}" y1="${a.y}"
              x2="${b.x}" y2="${b.y}">
              <title>${t("completed")}: ${n(edge.exchange_count)}</title>
            </line>`
          : "";
      }).join("")}

      ${nodes.map((node) => {
        const p = positions.get(node.id);
        const initials = String(node.name || "")
          .split(/\s+/).map((word) => word[0]).join("");

        return `
          <g>
            <circle cx="${p.x}" cy="${p.y}"
              r="${22 + Math.min((node.seed_lot_count || 0) * 2, 14)}">
              <title>${esc(node.name)}</title>
            </circle>
            <text x="${p.x}" y="${p.y + 4}" text-anchor="middle">
              ${esc(initials)}
            </text>
            <text class="node-name" x="${p.x}" y="${p.y + 49}"
              text-anchor="middle">${esc(node.name)}</text>
            <text x="${p.x}" y="${p.y + 66}" text-anchor="middle">
              ${n(node.seed_lot_count)} ${t("batches")}
            </text>
          </g>`;
      }).join("")}
    </svg>`;
}

