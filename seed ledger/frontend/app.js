/* ---------- Data loading ---------- */

async function load() {
  if (loading) return;

  loading = true;
  $("#refresh").disabled = true;
  $("#error").hidden = true;
  noticeKey = null;

  try {
    if (state.token) {
      try {
        state.me = await api("/auth/me");
      } catch (error) {
        if (![401, 403].includes(error.status)) throw error;

        state.me = null;
        state.token = null;
        removeStorage("sl_server_token", true);
      }
    } else {
      state.me = null;
    }

    const [
      stats, lots, growers, exchanges,
      activities, insights, graph,
    ] = await Promise.all([
      "/network/stats",
      "/seed-lots?limit=500",
      "/growers?limit=500",
      "/exchanges?limit=100",
      "/activities",
      "/insights",
      "/network/graph",
    ].map((path) => api(path)));

    Object.assign(state, {
      stats, lots, growers, exchanges,
      activities, insights, graph,
    });

    state.requests = state.me ? await api("/requests") : [];

    applyLanguage();
    render();
  } catch (error) {
    showError(error);
    renderGate();
  } finally {
    loading = false;
    $("#refresh").disabled = false;
  }
}

