document.addEventListener("click", async (event) => {
  const target = event.target;
  if (!(target instanceof Element)) return;

  try {
    const gate = target.closest("[data-gate]");

    if (gate) {
      gateTab = gate.dataset.gate;
      renderGate();
      return;
    }

    const saved = target.closest("[data-save]");

    if (saved) {
      const added = toggleSaved(Number(saved.dataset.save));
      toast(added ? "bookmarkAdded" : "bookmarkRemoved");
      filterLots();
      return;
    }

    const inbox = target.closest("[data-inbox]");

    if (inbox) {
      closeModal();
      navigate(inbox.dataset.inbox);
      return;
    }

    const page = target.closest("[data-page]");

    if (page) {
      navigate(page.dataset.page);
      return;
    }

    if (target.closest("#surprise")) {
      const pool = state.lots.filter(
        (lot) => lot.available_seeds > 0 && lot.is_available
      );

      if (!pool.length) {
        toast("empty");
        return;
      }

      await passport(pool[Math.floor(Math.random() * pool.length)].id);
      return;
    }

    const action = target.closest("[data-action]");

    if (action && !action.disabled) {
      await handleAction(
        action.dataset.action,
        Number(action.dataset.id)
      );
    }
  } catch (error) {
    showError(error);
  }
});

