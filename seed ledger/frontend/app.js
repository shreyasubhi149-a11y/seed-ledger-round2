function alertKeys(alert) {
  const title = String(alert.title || "").toLowerCase();

  if (title.includes("coverage")) {
    return ["coverage", "coverageInfo"];
  }

  if (title.includes("germination")) {
    return ["germReview", "germReviewInfo"];
  }

  if (title.includes("storage")) {
    return ["storageReview", "storageReviewInfo"];
  }

  return ["missingEvidence", "missingInfo"];
}

