const $ = (selector) => document.querySelector(selector);

function t(key, values = {}) {
  const index = LANGUAGES.findIndex(([code]) => code === language);
  const row = TEXT[key];
  let result = row ? row[index] || row[0] : key;

  for (const [name, value] of Object.entries(values)) {
    result = result.replaceAll(`{${name}}`, String(value));
  }

  return result;
}

function esc(value) {
  return String(value ?? "").replace(
    /[&<>"']/g,
    (character) => ({
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    })[character]
  );
}

function n(value) {
  return Number(value || 0).toLocaleString(LOCALES[language]);
}

function date(value) {
  if (!value) return t("notRecorded");

  let text = String(value);

  if (
    text.includes("T") &&
    !text.endsWith("Z") &&
    !/[+-]\d\d:\d\d$/.test(text)
  ) {
    text += "Z";
  }

  const parsed = new Date(text);

  return Number.isNaN(parsed.getTime())
    ? t("notRecorded")
    : parsed.toLocaleDateString(LOCALES[language], {
        day: "numeric",
        month: "short",
        year: "numeric",
      });
}

