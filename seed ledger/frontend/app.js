/* ---------- Language changes without losing form entries ---------- */

function captureForm(form) {
  return [...form.elements]
    .filter((element) => element.name)
    .map((element) => ({
      name: element.name,
      value: element.value,
      checked: element.checked,
      type: element.type,
    }));
}

function restoreForm(form, entries) {
  if (!form) return;

  const controls = [...form.elements];

  for (const entry of entries) {
    const element = controls.find((control) =>
      control.name === entry.name &&
      (
        !["checkbox", "radio"].includes(entry.type) ||
        control.value === entry.value
      )
    );

    if (!element) continue;

    if (["checkbox", "radio"].includes(entry.type)) {
      element.checked = entry.checked;
    } else {
      element.value = entry.value;
    }
  }
}

function rerenderModal(descriptor) {
  if (!descriptor) return;

  switch (descriptor.type) {
    case "account": accountModal(); break;
    case "lot": lotForm(); break;
    case "request": requestForm(descriptor.id); break;
    case "stock": stockForm(descriptor.id); break;
    case "report": reportForm(descriptor.id); break;
    case "decision":
      decisionForm(descriptor.id, descriptor.action);
      break;
    case "passport":
      modalDescriptor = descriptor;
      drawPassport(descriptor.data, descriptor.id);
      break;
    case "label": labelView(descriptor.id); break;
    case "inbox": openInbox(); break;
    case "about": aboutModal(); break;
    case "match":
      matchForm();
      if (descriptor.results) {
        drawMatches(descriptor.results);
        modalDescriptor = descriptor;
      }
      break;
  }
}

function setLanguage(value) {
  if (!LANGUAGES.some(([code]) => code === value)) return;

  const gateForm = $("#gate-step form");
  const gateValues = gateForm ? captureForm(gateForm) : [];

  const modalForm = $("#modal-content form");
  const modalValues = modalForm ? captureForm(modalForm) : [];
  const descriptor = modalDescriptor;

  const filters = state.page === "catalogue"
    ? {
        q: $("#search")?.value || "",
        availability: $("#availability")?.value || "all",
        sort: $("#sort")?.value || "new",
        min: $("#mingerm")?.value || "0",
      }
    : null;

  const tourWasOpen = !$("#tour").hidden;

  language = value;
  writeStorage("sl_lang", language);

  $("#toast").hidden = true;

  applyLanguage();
  render();

  restoreForm($("#gate-step form"), gateValues);

  if (filters) {
    $("#search").value = filters.q;
    $("#availability").value = filters.availability;
    $("#sort").value = filters.sort;
    $("#mingerm").value = filters.min;
    filterLots();
  }

  if ($("#modal").open && descriptor) {
    rerenderModal(descriptor);
    restoreForm($("#modal-content form"), modalValues);
  }

  if (tourWasOpen) showTour();
}

